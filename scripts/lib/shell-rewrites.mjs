import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Serve every corpus record address from one prerendered shell, without the
 * Worker.
 *
 * /hadith/<id>/ and /narrators/<id>/ used to be on-demand routes. They read
 * nothing at request time, but on-demand still meant a Worker invocation per
 * page view, and on 2026-10-19 crawlers walking the narrator sitemap took the
 * Worker past the Free plan's 100,000 daily requests (124,875). Each family is
 * now one page, /hadith/shell/ and /narrators/shell/, and a 200 rewrite in
 * `_redirects` serves it for every id. Cloudflare's static asset layer applies
 * `_redirects` before the Worker is considered, so these requests are asset
 * requests: free, unmetered, and never counted against the Worker.
 *
 * Rules written per family, after scripts/lib/slash-redirects.mjs has run:
 *
 *   /narrators/compare/ /narrators/compare/ 200   one per real sibling page
 *   /narrators/:id /narrators/:id/ 301            slashless address, as before
 *   /narrators/:id/ /narrators/shell/ 200         every other single segment
 *
 * A placeholder matches any segment, not just digits, and redirects apply
 * whether or not an asset exists at the address. So every page that really
 * lives one level under the prefix gets a rule serving itself first; the top
 * matching rule wins and proxies are not chained, so it is served unchanged.
 * Those are found in the build output rather than listed by hand, so a new
 * page under /hadith/ or /narrators/ cannot be swallowed by the shell.
 */

/** Families served from a shell, and the shell's own address. */
export const SHELL_FAMILIES = [
  { prefix: '/hadith', shell: '/hadith/shell/' },
  { prefix: '/narrators', shell: '/narrators/shell/' }
];

const MAX_STATIC_RULES = 2000;
const MAX_DYNAMIC_RULES = 100;

const isDynamicSource = (source) => source.includes('*') || /:[A-Za-z]/.test(source);

/** Single-segment pages the build wrote under a prefix, as slashed paths. */
function siblingPages(root, prefix) {
  const folder = path.join(root, prefix);
  if (!existsSync(folder)) return [];
  return readdirSync(folder, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(path.join(folder, entry.name, 'index.html')))
    .map((entry) => `${prefix}/${encodeURI(entry.name)}/`);
}

export function shellRewrites() {
  return {
    name: 'hadithcritic:shell-rewrites',
    hooks: {
      'astro:build:done': ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const redirectsPath = path.join(root, '_redirects');
        const existing = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8') : '';
        const sources = existing
          .split(/\r?\n/)
          .map((line) => line.trim())
          .filter((line) => line && !line.startsWith('#'))
          .map((line) => line.split(/\s+/)[0]);
        const taken = new Set(sources);

        const rules = [];
        for (const { prefix, shell } of SHELL_FAMILIES) {
          const siblings = siblingPages(root, prefix);
          if (!siblings.includes(shell)) {
            throw new Error(`The build has no ${shell}, so ${prefix}/<id>/ would be rewritten to nothing.`);
          }
          // The shell is served to itself too; a direct visit renders "not a reference".
          for (const page of siblings) rules.push(`${page} ${page} 200`);
          if (!taken.has(`${prefix}/:id`)) rules.push(`${prefix}/:id ${prefix}/:id/ 301`);
          rules.push(`${prefix}/:id/ ${shell} 200`);
        }

        for (const rule of rules) {
          const source = rule.split(' ')[0];
          if (taken.has(source)) throw new Error(`_redirects already has a rule for ${source}.`);
          taken.add(source);
        }

        // Cloudflare counts every line after the first dynamic one as dynamic,
        // and these come last, so all of them count against that limit.
        const firstDynamic = sources.findIndex(isDynamicSource);
        const staticCount = firstDynamic === -1 ? sources.length : firstDynamic;
        const dynamicCount = sources.length - staticCount + rules.length;
        if (staticCount > MAX_STATIC_RULES || dynamicCount > MAX_DYNAMIC_RULES) {
          throw new Error(
            `_redirects would hold ${staticCount} static rules (limit ${MAX_STATIC_RULES}) and ` +
            `${dynamicCount} dynamic rules (limit ${MAX_DYNAMIC_RULES}); Cloudflare would refuse the deploy.`
          );
        }

        const header = '# Generated by scripts/lib/shell-rewrites.mjs: corpus records served from their shells.';
        writeFileSync(redirectsPath, `${existing.replace(/\s*$/, '\n')}\n${header}\n${rules.join('\n')}\n`);
        logger.info(`Wrote ${rules.length} shell rules; _redirects holds ${dynamicCount}/${MAX_DYNAMIC_RULES} dynamic rules`);
      }
    }
  };
}

/**
 * The same rewrite under `astro dev`, which never reads `_redirects`. Only
 * numeric segments are rewritten here; anything else falls through to the
 * dev server's own routes and its 404.
 */
export function shellDevServer() {
  const pattern = new RegExp(
    `^(${SHELL_FAMILIES.map(({ prefix }) => prefix.replace(/\//g, '\\/')).join('|')})\\/\\d+\\/?(?=$|[?#])`
  );
  return {
    name: 'hadithcritic:shell-dev-server',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use((req, _res, next) => {
        const url = req.url ?? '';
        const match = pattern.exec(url);
        if (match) req.url = `${match[1]}/shell/${url.slice(match[0].length)}`;
        next();
      });
    }
  };
}

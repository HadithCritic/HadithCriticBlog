import { appendFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Turn the host's temporary trailing-slash redirect into a permanent one.
 *
 * Every prerendered page is written as <path>/index.html, and Cloudflare's
 * static assets answer a request for <path> with a 307 to <path>/. A 307 tells
 * a search engine the move is temporary, so the slashless URL keeps competing
 * with the real one instead of consolidating into it. Nothing in the asset
 * configuration changes that status.
 *
 * `_redirects` is applied before that normalization, so an exact rule per page
 * (`/academia /academia/ 301`) wins. It has to be exact: a wildcard such as
 * `/blogs/* /blogs/:splat/ 301` also matches the slashed URL and redirects it
 * to itself. Both were checked against `astro preview`, which runs the same
 * asset handling as production.
 *
 * The rules are generated after the build from the pages that were actually
 * written, so a new page is covered without anyone editing a list. Cloudflare
 * allows 2,000 static rules; the site uses about 540 with this.
 */
export function slashRedirects() {
  return {
    name: 'hadithcritic:slash-redirects',
    hooks: {
      'astro:build:done': ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const pages = [];

        const walk = (folder) => {
          for (const name of readdirSync(folder)) {
            const full = path.join(folder, name);
            if (statSync(full).isDirectory()) walk(full);
            else if (name === 'index.html' && folder !== root) {
              pages.push('/' + path.relative(root, folder).split(path.sep).join('/'));
            }
          }
        };
        walk(root);

        const rules = pages
          .sort()
          .map((page) => `${encodeURI(page)} ${encodeURI(page)}/ 301`);

        appendFileSync(
          path.join(root, '_redirects'),
          `\n# Generated by scripts/lib/slash-redirects.mjs: 301 each page to its trailing-slash URL.\n${rules.join('\n')}\n`
        );
        logger.info(`Added ${rules.length} trailing-slash redirects to _redirects`);
      }
    }
  };
}

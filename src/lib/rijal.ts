export function symbolLabel(sym: string): string {
  return SYMBOL_MAP[sym] ?? 'Ancillary collection (siglum ' + sym + ')';
}

/* Short form of a name for searching Silsilah chains: first few name words. */
export function searchName(name: string): string {
  return name.split(/\s+/).slice(0, 4).join(' ');
}

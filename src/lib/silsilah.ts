const escapeHtml = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* Escape, then render the light markup the corpus uses: *emphasis* pairs. */
export function renderRich(text: string | null): string {
  if (!text) return '';
  let out = escapeHtml(text);
  out = out.replace(/\*([^*]+)\*/g, '<em>$1</em>');
  return out;
}

export type GradeTone = 'sound' | 'good' | 'weak' | 'bad' | 'none';

export function gradeTone(gradeEn: string | null): GradeTone {
  if (!gradeEn) return 'none';
  const g = gradeEn.toLowerCase();
  if (g.includes('fabricat') || g.includes('rejected') || g.includes('repudiated') || g.includes('baseless')) return 'bad';
  if (g.includes('weak')) return 'weak';
  if (g.includes('agreed') || g.includes('sound') || g.includes('corroborated')) return 'sound';
  if (g.includes('good') || g.includes('fair')) return 'good';
  if (g.includes('no grade') || g.includes('silent')) return 'none';
  return 'none';
}

/* "A > B > C" or "[Chain 1] A > B [Chain 2] C > D" -> list of chains of narrators */
export function parseChains(chainEn: string | null): string[][] {
  if (!chainEn) return [];
  const parts = chainEn.split(/\[Chain \d+\]/).map((p) => p.trim()).filter(Boolean);
  return parts.map((p) =>
    p.split('>').map((n) => n.trim()).filter(Boolean)
  );
}

export function translationLabel(c: CollectionInfo): { label: string; tone: 'full' | 'partial' | 'none' } {
  if (c.englishPct < 5) return { label: 'Arabic only', tone: 'none' };
  const aiShare = c.englishCount ? c.aiCount / c.englishCount : 0;
  if (aiShare > 0.5) return { label: 'English (largely AI-assisted)', tone: 'partial' };
  if (aiShare > 0.1) return { label: 'English (partly AI-assisted)', tone: 'partial' };
  return { label: 'Full English translation', tone: 'full' };
}

export function fmtCount(n: number): string {
  return n.toLocaleString('en-US');
}

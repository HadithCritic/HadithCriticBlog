export type Entry = ChapterEntry | HadithEntry;

export interface BookData {
  h1: string | null;
  slug: string;
  ordinal: number;
  titleEn: string | null;
  titleAr: string | null;
  introEn: string | null;
  introAr: string | null;
  count: number;
  pages: Entry[][];
}

let indexCache: { collections: CollectionInfo[] } | null = null;

export function loadIndex(): { collections: CollectionInfo[] } {
  if (!indexCache) {
    indexCache = JSON.parse(readFileSync(path.join(DATA_DIR, 'index.json'), 'utf8'));
  }
  return indexCache!;
}

const bookCache = new Map<string, BookData>();

export function loadBook(collection: string, bookSlug: string): BookData {
  const key = collection + '/' + bookSlug;
  let b = bookCache.get(key);
  if (!b) {
    b = JSON.parse(
      readFileSync(path.join(DATA_DIR, collection, 'book-' + bookSlug + '.json'), 'utf8')
    ) as BookData;
    // keep memory bounded during the static build
    if (bookCache.size > 3) bookCache.clear();
    bookCache.set(key, b);
  }
  return b;
}


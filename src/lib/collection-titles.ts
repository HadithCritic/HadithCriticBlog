export function getTransliteratedTitle(nameEn: string | null, authorEn: string | null): string {
  if (!nameEn) return '';
  const cleanName = nameEn.trim();
  
  // Ambiguous names handling
  if (cleanName === "Book") {
    if (authorEn === "Ibn Tihman") return "Kitāb Ibn Tihmān";
    if (authorEn === "Hammam ibn Munabbih") return "Ṣaḥīfat Hammām ibn Munabbih";
    if (authorEn === "Ibn al-Mubarak") return "Kitāb Ibn al-Mubārak";
  }
  
  if (cleanName === "Jihad" && authorEn === "Ibn al-Mubarak") {
    return "Kitāb al-Jihād li-Ibn al-Mubārak";
  }

  if (cleanName === "The Comprehensive Collection") {
    if (authorEn === "Maʿmar ibn Rāshid") return "al-Jāmiʿ li-Maʿmar ibn Rāshid";
    if (authorEn === "Ibn Wahb") return "al-Jāmiʿ li-Ibn Wahb";
  }

  if (cleanName === "The Musannaf") {
    if (authorEn === "Abd al-Razzaq al-Sanʿani") return "al-Muṣannaf li-ʿAbd al-Razzāq al-Ṣanʿānī";
    if (authorEn === "Abu Bakr ibn Abi Shaybah") return "al-Muṣannaf li-Ibn Abī Shayba";
  }

  return TRANSLITERATED_TITLES[cleanName] || cleanName;
}
